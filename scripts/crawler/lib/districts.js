/** [정규식, 시도] 목록. 긴 이름이 먼저 오도록 정렬합니다. */
const DISTRICT_PATTERNS = Object.entries(DISTRICTS)
  .flatMap(([region, names]) =>
    names.map((name) => {
      const source = RISKY.has(name) ? `${name}(?:시|군|구)` : name;
      return { name, region, regex: new RegExp(source) };
    })
  )
  .sort((a, b) => b.name.length - a.name.length);

